#!/usr/bin/env python3
"""
The Backstory draft (T-0109): the publish-time Backstory steps, run before publish, shipped at publish.

  make   after build_pairings.py and build_origins.py have run on COPIES of backstory.json and
         provisional-rows.json against Pulse's draft lineup, collect what they chose into
         ntk-pulse/data/backstory-draft.json. Live files are never touched.
  apply  at publish, before those two steps. If every story in lineup-publish.json carries the same
         bs_hash it carried in the draft, write the draft's results into the live files and report
         used=true, so the workflow skips the two steps and nothing is chosen twice. Otherwise report
         used=false and change nothing: publish chooses as it always has.

bs_hash is written by Pulse (one implementation, in JavaScript) over the fields that decide a story's
Backstory: its text, the row the editor filed it under, and that category's record as Pulse sends it.
This script only compares the strings.

  python3 editorial/backstory_draft.py make  --lineup L --backstory B --provisional P --origins O --branch staging
  python3 editorial/backstory_draft.py apply [--github-output "$GITHUB_OUTPUT"]

Stdlib only.
"""
import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DRAFT = ROOT / "ntk-pulse" / "data" / "backstory-draft.json"
LINEUP = ROOT / "ntk-pulse" / "data" / "lineup-publish.json"
BACKSTORY = ROOT / "digest" / "data" / "backstory.json"
PROVISIONAL = ROOT / "ntk-pulse" / "data" / "provisional-rows.json"
ORIGINS = ROOT / "editorial" / "origins.json"


def log(msg):
    print(msg, file=sys.stderr)


def load(p):
    return json.loads(Path(p).read_text())


def dump(p, d, indent=2):
    Path(p).write_text(json.dumps(d, indent=indent, ensure_ascii=False) + "\n")


def make(args):
    lineup, bs, prov = load(args.lineup), load(args.backstory), load(args.provisional)
    origins = load(args.origins) if Path(args.origins).exists() else {"origins": []}
    rows = {r["id"]: r for r in bs.get("rows", [])}
    pairs = {p["story_id"]: p for p in bs.get("todays_pairings", [])}
    stories = []
    for s in lineup.get("stories", []):
        p = pairs.get(s["key"])
        r = rows.get(p["row"]) if p else None
        stories.append({
            "story_id": s["key"], "headline": s.get("headline", ""), "bs_hash": s.get("bs_hash"),
            "bs_text_hash": s.get("bs_text_hash"),
            "pairing": p,
            # what the reader's page draws: the category as this run left it
            "row": {k: r.get(k) for k in ("id", "title", "stratum", "start_date", "start_line", "stakes",
                                          "milestone", "beginnings", "objects", "indicator", "auto")} if r else None,
            "status": "paired" if p else "no pairing",
        })
    draft = {
        "_comment": "Generated by editorial/backstory_draft.py (T-0109). Pulse shows it; publish ships it when nothing changed.",
        "generated": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "branch": args.branch,
        "stories": stories,
        # what publish writes back when it ships the draft
        "ship": {
            "todays_pairings": bs.get("todays_pairings", []),
            "pairings_generated": bs.get("pairings_generated"),
            "provisional_rows": [r for r in bs.get("rows", []) if r.get("stratum") == "provisional"],
            "provisional_store": prov,
            "origins": origins,
        },
    }
    dump(args.out, draft, indent=1)
    log(f"draft: {len(stories)} stories, {sum(1 for s in stories if s['pairing'])} paired -> {args.out}")


def matches(draft, lineup):
    """Why the draft cannot ship, or [] when it can."""
    want = {s["key"]: s.get("bs_hash") for s in lineup.get("stories", [])}
    have = {s["story_id"]: s.get("bs_hash") for s in draft.get("stories", [])}
    why = []
    for k, h in want.items():
        if not h:
            why.append(f"{k}: no bs_hash in the lineup")
        elif k not in have:
            why.append(f"{k}: not in the draft")
        elif have[k] != h:
            why.append(f"{k}: changed since the draft")
    for k in have:
        if k not in want:
            why.append(f"{k}: in the draft, not in the lineup")
    return why


def apply(args):
    used = False
    if not Path(args.draft).exists():
        log("no Backstory draft; publish chooses as usual")
    else:
        draft, lineup = load(args.draft), load(args.lineup)
        why = matches(draft, lineup)
        if why:
            log("Backstory draft not used, publish chooses again:\n  " + "\n  ".join(why))
        else:
            ship = draft["ship"]
            bs = load(args.backstory)
            bs["rows"] = [r for r in bs["rows"] if r.get("stratum") != "provisional"] + ship["provisional_rows"]
            # T-0110: each story's own page, as composed and edited in the draft, travels on its pairing
            composed = {d["story_id"]: d["composed"] for d in draft["stories"]
                        if d.get("composed") and not d["composed"].get("error")}
            for p in ship["todays_pairings"]:
                if p["story_id"] in composed:
                    p["composed"] = {k: v for k, v in composed[p["story_id"]].items()
                                     if k not in ("notes", "usage", "shortlist", "model")}
            bs["todays_pairings"] = ship["todays_pairings"]
            bs["pairings_generated"] = ship["pairings_generated"]
            dump(args.backstory, bs)
            dump(args.provisional, ship["provisional_store"])
            dump(args.origins, ship["origins"], indent=1)
            used = True
            log(f"Backstory draft of {draft.get('generated')} shipped: {len(ship['todays_pairings'])} pairings")
    if args.github_output:
        with open(args.github_output, "a") as f:
            f.write(f"used={'true' if used else 'false'}\n")
    print("used" if used else "not used")


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    m = sub.add_parser("make")
    m.add_argument("--lineup", required=True)
    m.add_argument("--backstory", required=True)
    m.add_argument("--provisional", required=True)
    m.add_argument("--origins", required=True)
    m.add_argument("--branch", default="")
    m.add_argument("--out", default=str(DRAFT))
    a = sub.add_parser("apply")
    a.add_argument("--draft", default=str(DRAFT))
    a.add_argument("--lineup", default=str(LINEUP))
    a.add_argument("--backstory", default=str(BACKSTORY))
    a.add_argument("--provisional", default=str(PROVISIONAL))
    a.add_argument("--origins", default=str(ORIGINS))
    a.add_argument("--github-output")
    args = ap.parse_args()
    make(args) if args.cmd == "make" else apply(args)


if __name__ == "__main__":
    main()
